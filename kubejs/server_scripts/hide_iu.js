// Все id предметов из блока выхода рецепта (result, results, output, outputs и их вложенные поля).
function hideIuCollect(el, acc) {
  if (el == null || el.isJsonNull()) return
  if (el.isJsonPrimitive()) {
    acc.push(String(el.getAsString()))
  } else if (el.isJsonArray()) {
    for (var i = 0; i < el.size(); i++) hideIuCollect(el.get(i), acc)
  } else if (el.isJsonObject()) {
    var it = el.keySet().iterator()
    while (it.hasNext()) hideIuCollect(el.get(it.next()), acc)
  }
}

var HIDE_IU_OUT_KEYS = ['result', 'results', 'output', 'outputs']

ServerEvents.recipes(function (event) {
  var set = {}
  HIDE_IU.forEach(function (id) { set[id] = true })
  var toRemove = []
  event.forEachRecipe({}, function (r) {
    try {
      var json = r.json
      var outs = []
      HIDE_IU_OUT_KEYS.forEach(function (k) {
        if (json.has(k)) hideIuCollect(json.get(k), outs)
      })
      for (var i = 0; i < outs.length; i++) {
        if (set[outs[i]]) {
          toRemove.push(String(r.getId()))
          return
        }
      }
    } catch (e) {
      console.error('[hide_iu] read failed ' + r.getId() + ': ' + e)
    }
  })
  toRemove.forEach(function (id) {
    event.remove({ id: id })
  })
  console.info('[hide_iu] items: ' + HIDE_IU.length + ', recipes removed: ' + toRemove.length)
})

// Проверка после загрузки: рецептов с этими предметами на выходе не осталось.
ServerEvents.loaded(function (event) {
  try {
    var set = {}
    HIDE_IU.forEach(function (id) { set[id] = true })
    var left = []
    var reg = event.server.registryAccess()
    event.server.recipeManager.getRecipes().forEach(function (holder) {
      try {
        var stack = holder.value().getResultItem(reg)
        var id = String(stack.getItem().builtInRegistryHolder().key().location())
        if (set[id]) left.push(String(holder.id()) + ' -> ' + id)
      } catch (e) {}
    })
    if (left.length) console.error('[hide_iu] recipes left: ' + left.length + ': ' + left.slice(0, 20).join(', '))
    console.info('[hide_iu] check: recipes with hidden output left ' + left.length)
  } catch (e) {
    console.error('[hide_iu] check failed: ' + e)
  }
})
