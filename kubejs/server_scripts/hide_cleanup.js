// Сервер: удалить рецепты, у которых ВСЕ выходы из списка (рецепт с нужной побочкой остаётся).
function hideCleanupOuts(el, acc, out) {
  if (el == null || el.isJsonNull()) return
  if (el.isJsonPrimitive()) { if (out) acc.push(String(el.getAsString())) }
  else if (el.isJsonArray()) { for (var i = 0; i < el.size(); i++) hideCleanupOuts(el.get(i), acc, out) }
  else { var it = el.keySet().iterator(); while (it.hasNext()) { var k = String(it.next()); hideCleanupOuts(el.get(k), acc, out || /result|output|product/i.test(k)) } }
}
ServerEvents.recipes(function (event) {
  var set = {}, del = []
  HIDE_CLEANUP.forEach(function (id) { set[id] = true })
  event.forEachRecipe({}, function (r) {
    var outs = []
    try { hideCleanupOuts(r.json, outs, false) } catch (e) { return }
    outs = outs.filter(function (o) { return o.indexOf(":") > 0 && o.charAt(0) != "#" })
    if (outs.length && outs.every(function (o) { return set[o] })) del.push(String(r.getId()))
  })
  del.forEach(function (id) { event.remove({ id: id }) })
  var bad = HIDE_CLEANUP.filter(function (id) { return Item.of(id).isEmpty() })
  console.info('[check] hide_cleanup: ' + HIDE_CLEANUP.length + ' items, recipes removed ' + del.length + (bad.length ? ', not found: ' + bad.join(', ') : ''))
})
