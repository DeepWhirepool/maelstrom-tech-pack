// Все id предметов в полях выхода рецепта (result/output/product на любой глубине, напр. recipe.result у Forestry).
function hideDecorCollect(el, acc, inOut) {
  if (el == null || el.isJsonNull()) return
  if (el.isJsonPrimitive()) {
    if (inOut) acc.push(String(el.getAsString()))
  } else if (el.isJsonArray()) {
    for (var i = 0; i < el.size(); i++) hideDecorCollect(el.get(i), acc, inOut)
  } else if (el.isJsonObject()) {
    var it = el.keySet().iterator()
    while (it.hasNext()) {
      var k = String(it.next())
      hideDecorCollect(el.get(k), acc, inOut || /result|output|product/i.test(k))
    }
  }
}

ServerEvents.recipes(function (event) {
  var set = {}
  HIDE_DECOR.forEach(function (id) { set[id] = true })
  var toRemove = []
  event.forEachRecipe({}, function (r) {
    try {
      var outs = []
      hideDecorCollect(r.json, outs, false)
      for (var i = 0; i < outs.length; i++) {
        if (set[outs[i]]) {
          toRemove.push(String(r.getId()))
          return
        }
      }
    } catch (e) {
      console.error('[hide_decor] read failed ' + r.getId() + ': ' + e)
    }
  })
  toRemove.forEach(function (id) { event.remove({ id: id }) })
  console.info('[hide_decor] items: ' + HIDE_DECOR.length + ', recipes removed: ' + toRemove.length)
})
