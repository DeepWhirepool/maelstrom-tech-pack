RecipeViewerEvents.removeEntries('fluid', function (event) {
  var used = {}, n = 0
  HIDE_IC2_FLUIDS.forEach(function (id) { used['industrialupgrade:' + id] = true })
  Java.loadClass('net.minecraft.core.registries.BuiltInRegistries').FLUID.keySet().forEach(function (k) {
    k = String(k)
    if (k.indexOf('industrialupgrade:') == 0 && !used[k]) try { event.remove(k); n++ } catch (e) {}
  })
  console.info('[hide_ic2] JEI fluids hidden: ' + n + ' (used ' + HIDE_IC2_FLUIDS.length + ')')
})

RecipeViewerEvents.removeEntries('item', function (event) {
  var n = 0
  Java.loadClass('net.minecraft.core.registries.BuiltInRegistries').ITEM.keySet().forEach(function (k) {
    if (hideIc2(k)) try { event.remove(String(k)); n++ } catch (e) {}
  })
  console.info('[hide_ic2] JEI items hidden: ' + n)
})

// Категории: в removeCategories рантайм JEI ещё не готов (Internal.setRuntime идёт после плагинов) — ждём его на тике.
var HIDE_IC2_JEI = Java.loadClass('mezz.jei.common.Internal'), hideIc2Rt = null
ClientEvents.tick(function () {
  var o = HIDE_IC2_JEI.getOptionalJeiRuntime()
  if (!o.isPresent() || o.get() === hideIc2Rt) return
  hideIc2Rt = o.get()
  var rm = hideIc2Rt.getRecipeManager(), hide = []
  rm.createRecipeCategoryLookup().get().forEach(function (c) {
    var t = c.getRecipeType()
    if (String(t.getUid().getNamespace()) != 'industrialupgrade') return
    var cat = []
    rm.createRecipeCatalystLookup(t).getItemStack().forEach(function (s) { cat.push(String(s.id)) })
    if (rm.createRecipeLookup(t).get().count() == 0 || (cat.length && cat.every(hideIc2))) hide.push(t)
  })
  hide.forEach(function (t) { rm.hideRecipeCategory(t) })
  console.info('[hide_ic2] JEI categories hidden: ' + hide.length)
})
